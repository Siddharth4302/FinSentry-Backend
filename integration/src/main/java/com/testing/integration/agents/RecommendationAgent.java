package com.testing.integration.agents;

import com.testing.integration.dtos.FinancialRiskAssessment;
import com.testing.integration.service.GroqService;

import org.springframework.stereotype.Service;

@Service
public class RecommendationAgent {

    private final GroqService groqService;

    public RecommendationAgent(GroqService groqService) {
        this.groqService = groqService;
    }

    public String refineRecommendations(
            FinancialRiskAssessment assessment) {

        if (assessment == null) {
            throw new IllegalArgumentException(
                    "Financial risk assessment cannot be null"
            );
        }

        String systemPrompt = """
                You are FinSentry's Recommendation Agent.

                Your responsibility is to refine and prioritize
                recommendations generated by the Policy Agent.

                The Policy Agent is the authoritative source for
                financial policy decisions and supported actions.

                Follow these rules strictly:

                1. Do not introduce new financial actions.
                2. Do not modify policy thresholds.
                3. Do not override the Policy Agent's decisions.
                4. Preserve the meaning of every recommendation.
                5. Remove unnecessary repetition.
                6. Make recommendations clear, concise and actionable.
                7. Prioritize recommendations based on the assessed risk.
                8. Clearly distinguish preventive monitoring from
                   policy-triggered actions.
                9. Do not treat potential root causes as confirmed facts.
                10. Every recommendation requires human review
                    before execution.
                11. If the financial health score is unavailable,
                    do not estimate or invent one.

                Priority definitions:
                - HIGH: An applicable policy-triggered action requiring
                  timely human review.
                - MEDIUM: Preventive monitoring or information gathering.
                - LOW: Other non-urgent follow-up actions.

                Return ONLY valid JSON.
                Do not use Markdown or code fences.

                Use exactly this JSON structure:

                {
                  "recommendations": [
                    {
                      "priority": "HIGH",
                      "category": "POLICY_TRIGGERED",
                      "action": "string",
                      "rationale": "string",
                      "humanReviewRequired": true
                    }
                  ],
                  "humanReviewRequired": true
                }

                Do not create recommendations that are not supported
                by the Policy Agent's assessment.
                """;

        String financialHealthScore =
                assessment.financialHealthScore() != null
                        ? assessment.financialHealthScore().toString()
                        : "Not available";

        String riskFactors =
                assessment.riskFactors() != null
                        ? String.join("\n", assessment.riskFactors())
                        : "None provided";

        String recommendedActions =
                assessment.recommendedActions() != null
                        ? String.join("\n", assessment.recommendedActions())
                        : "None provided";

        String sources =
                assessment.sources() != null
                        ? String.join("\n", assessment.sources())
                        : "None provided";

        String userPrompt = """
                Refine the following policy-validated financial assessment.

                Financial Health Score: %s
                Risk Level: %s

                Risk Factors:
                %s

                Root Cause Assessment:
                %s

                Policy Agent Recommendations:
                %s

                Sources:
                %s

                Human Review Required: %s

                Refine and prioritize the existing recommendations.
                Do not introduce new actions or unsupported policy rules.
                """.formatted(
                financialHealthScore,
                assessment.riskLevel(),
                riskFactors,
                assessment.rootCause(),
                recommendedActions,
                sources,
                assessment.humanReviewRequired()
        );

        return groqService.chat(systemPrompt, userPrompt);
    }
}